"""Supabase/Postgres storage adapter; explicit file paths are isolated test fixtures.

Application SQL keeps its existing bound '?' parameters. No parameter value is
interpolated. Runtime callers must supply the server-side SUPABASE_DB_URL.
"""
from collections.abc import Mapping
from contextlib import contextmanager
from pathlib import Path
import re
import sqlite3
from urllib.parse import urlsplit


class DatabaseError(RuntimeError):
    pass


def database_url(env):
    value = env.get('SUPABASE_DB_URL', '')
    try:
        parsed = urlsplit(value)
        valid = (parsed.scheme in ('postgres', 'postgresql') and parsed.hostname
                 and parsed.username and parsed.password and parsed.path.strip('/'))
    except ValueError:
        valid = False
    if not valid or any(x in value for x in ('[YOUR', 'YOUR_PASSWORD', 'your-complete-connection')):
        raise DatabaseError('Set a complete server-side SUPABASE_DB_URL in the root .env (value hidden).')
    return value


def postgres_sql(statement):
    statement=re.sub(r'\bs\.rowid\b','s.insertion_order',statement)
    ignore = bool(re.match(r'\s*INSERT OR IGNORE\b', statement, re.I))
    statement = re.sub(r'\bINSERT OR IGNORE\b', 'INSERT', statement, flags=re.I)
    # Keep literal question marks and escaped SQL quotes intact.
    result, quoted, i = [], None, 0
    while i < len(statement):
        char = statement[i]
        if quoted:
            result.append(char)
            if char == quoted:
                if i + 1 < len(statement) and statement[i + 1] == quoted:
                    result.append(statement[i + 1]); i += 1
                else:
                    quoted = None
        elif char in ("'", '"'):
            quoted = char; result.append(char)
        else:
            result.append('%s' if char == '?' else char)
        i += 1
    sql = ''.join(result)
    if ignore:
        sql = sql.rstrip().rstrip(';') + ' ON CONFLICT DO NOTHING'
    return sql


class Row(Mapping):
    def __init__(self, names, values):
        self.names, self.values = names, values
        self.mapping = dict(zip(names, values))
    def __getitem__(self, key):
        return self.values[key] if isinstance(key, int) else self.mapping[key]
    def __iter__(self):
        return iter(self.mapping)
    def __len__(self):
        return len(self.mapping)


class Cursor:
    def __init__(self, cursor):
        self.cursor = cursor
    @property
    def rowcount(self):
        return self.cursor.rowcount
    def _row(self, value):
        return None if value is None else Row([c.name for c in self.cursor.description], value)
    def fetchone(self):
        return self._row(self.cursor.fetchone())
    def fetchall(self):
        return [self._row(value) for value in self.cursor.fetchall()]
    def __iter__(self):
        for value in self.cursor:
            yield self._row(value)


class Connection:
    def __init__(self, connection):
        self.connection = connection
    def execute(self, statement, values=None):
        return Cursor(self.connection.execute(postgres_sql(statement), values))
    def executemany(self, statement, values):
        cursor = self.connection.cursor()
        cursor.executemany(postgres_sql(statement), values)
        return Cursor(cursor)
    def executescript(self, script):
        script = script.replace('id INTEGER PRIMARY KEY,', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,')
        self.connection.execute(script, prepare=False)


class Database:
    def __init__(self, target, schema='caspy'):
        if not re.fullmatch(r'caspy(?:_test_[a-f0-9]+)?',schema):
            raise DatabaseError('Unexpected application schema.')
        self.schema=schema
        self.postgres = str(target).startswith(('postgres://', 'postgresql://'))
        self.target = target
        if self.postgres:
            import psycopg
            self.integrity_error = psycopg.IntegrityError
        else:
            # Only callers explicitly passing a file path (unit-test fixtures)
            # can use SQLite. The game API never falls back to a local file.
            self.target = Path(target)
            self.target.parent.mkdir(parents=True, exist_ok=True)
            self.target.touch(mode=0o600, exist_ok=True)
            self.target.chmod(0o600)
            self.integrity_error = sqlite3.IntegrityError

    @contextmanager
    def connect(self):
        if self.postgres:
            import psycopg
            try:
                connection = psycopg.connect(self.target, sslmode='require', connect_timeout=10,
                                            prepare_threshold=None, application_name='caspy-api')
            except psycopg.Error:
                raise DatabaseError('Supabase connection failed; check network and server-side configuration (details hidden).') from None
            with connection:
                from psycopg import sql
                connection.execute(sql.SQL('SET LOCAL search_path TO {}, pg_catalog').format(sql.Identifier(self.schema)))
                connection.execute('SET LOCAL extra_float_digits=3')
                # Serializes cross-process transactions as well as this process's
                # RLock, preserving existing quota/read-then-write invariants.
                connection.execute('SELECT pg_advisory_xact_lock(743029154)')
                yield Connection(connection)
        else:
            connection = sqlite3.connect(self.target, timeout=10)
            connection.row_factory = sqlite3.Row
            connection.execute('PRAGMA foreign_keys=ON')
            try:
                with connection:
                    yield connection
            finally:
                connection.close()
