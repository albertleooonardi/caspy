#!/usr/bin/env python3
"""Offline SQLite → private Supabase schemas, verified before optional removal.

Run with the launcher stopped. Every original database (including old snapshots)
is retained losslessly in caspy_archive.sqlite_exports before native imports.
No credentials or row bodies are printed. This is not an app startup hook.
"""
import argparse
import base64
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import re
import secrets
import shutil
import socket
import sqlite3
import tempfile
from urllib.parse import unquote, urlsplit, urlunsplit, quote

import psycopg
from psycopg import sql
from psycopg.types.json import Jsonb
from bifrost_setup import ROOT, environment, private_write
from database import database_url


def encode(value):
    if isinstance(value, bytes): return {'$bytes': base64.b64encode(value).decode()}
    if isinstance(value, dt.datetime): return value.astimezone(dt.timezone.utc).isoformat()
    return value


def digest(value):
    return hashlib.sha256(json.dumps(value, default=encode, sort_keys=True, ensure_ascii=False,
                                     separators=(',', ':'), allow_nan=False).encode()).hexdigest()


def stopped():
    for port in (8000, 8080):
        with socket.socket() as connection:
            connection.settimeout(.3)
            if connection.connect_ex(('127.0.0.1', port)) == 0:
                raise RuntimeError('Stop Caspy and Bifrost before migrating or removing SQLite.')


def snapshot(path):
    # Read from a quiescent disposable copy, including WAL. Old read-only snapshot
    # directories cannot always create the SHM file SQLite needs for WAL reads.
    with tempfile.TemporaryDirectory(prefix='caspy-db-copy-') as folder:
        target = Path(folder)/path.name
        for suffix in ('', '-wal', '-shm'):
            source = Path(str(path)+suffix)
            if source.exists(): shutil.copy2(source, Path(str(target)+suffix))
        connection = sqlite3.connect(target)
        connection.row_factory = sqlite3.Row
        tables = []
        for row in connection.execute("SELECT name,sql FROM sqlite_master WHERE type='table' ORDER BY name").fetchall():
            name = row['name']; quoted = '"'+name.replace('"','""')+'"'
            columns = [list(r) for r in connection.execute('PRAGMA table_info('+quoted+')')]
            rows = [list(r) for r in connection.execute('SELECT * FROM '+quoted)]
            indexes=[]
            for idx in connection.execute('PRAGMA index_list('+quoted+')').fetchall():
                parts=[list(r) for r in connection.execute('PRAGMA index_info("'+idx['name'].replace('"','""')+'")')]
                definition=connection.execute('SELECT sql FROM sqlite_master WHERE type=\'index\' AND name=?',(idx['name'],)).fetchone()
                indexes.append({'name':idx['name'],'unique':idx['unique'],'partial':idx['partial'],'parts':parts,
                                'ddl':definition[0] if definition else None})
            foreign_keys=[list(r) for r in connection.execute('PRAGMA foreign_key_list('+quoted+')')]
            tables.append(dict(name=name,ddl=row['sql'],columns=columns,rows=rows,indexes=indexes,foreign_keys=foreign_keys))
        connection.close()
    # Encode binary values in both the stored payload and expected digest.
    return json.loads(json.dumps({'tables':tables},default=encode,ensure_ascii=False,allow_nan=False))


def discovered():
    found=[]
    for path in (ROOT/'data').rglob('*'):
        if path.is_file():
            with path.open('rb') as handle: header=handle.read(16)
            if header == b'SQLite format 3\0': found.append(path)
    return sorted(found)


def connect(dsn):
    return psycopg.connect(dsn, sslmode='require', connect_timeout=10, prepare_threshold=None,
                           application_name='caspy-migration')


def role_url(dsn, role, password):
    url=urlsplit(dsn)
    # Supabase shared poolers route custom users as role.project-ref.
    username=unquote(url.username)
    suffix='.'+username.split('.',1)[1] if '.pooler.supabase.com' in url.hostname and '.' in username else ''
    netloc=f'{quote(role+suffix,safe="")}:{quote(password,safe="")}@{url.hostname}:{url.port or 5432}'
    return urlunsplit((url.scheme,netloc,url.path,url.query,''))


def pgtype(declared, table, field, identity):
    kind=declared.lower()
    if identity: return 'BIGINT GENERATED BY DEFAULT AS IDENTITY'
    if kind in ('numeric','boolean','bool'): return 'BOOLEAN'
    if 'int' in kind: return 'BIGINT'
    if kind in ('datetime','timestamp'): return 'TIMESTAMPTZ'
    if kind in ('real','float','double'): return 'DOUBLE PRECISION'
    if kind in ('blob','bytea'): return 'BYTEA'
    if kind.startswith(('varchar(','char(')) and re.fullmatch(r'(?:var)?char\(\d+\)',kind): return kind.upper()
    return 'TEXT'


def cell(value, kind):
    if value is None: return None
    if isinstance(value,dict) and '$bytes' in value: return base64.b64decode(value['$bytes'])
    if kind=='BOOLEAN': return bool(value)
    if kind=='TIMESTAMPTZ':
        # SQLite/Go timestamps may include an offset and trailing zone abbreviation.
        text=str(value).removesuffix(' UTC')
        text=re.sub(r' ([+-]\d\d)(\d\d)$',r'\1:\2',text)
        # Python 3.9 accepts only 3/6 fractional digits, while Go/SQLite writes
        # variable precision. PostgreSQL timestamps retain microsecond precision.
        text=re.sub(r'\.(\d+)',lambda m:'.'+(m[1]+'000000')[:6],text)
        parsed=dt.datetime.fromisoformat(text.replace('Z','+00:00'))
        return parsed.replace(tzinfo=dt.timezone.utc) if parsed.tzinfo is None else parsed
    return value


def import_native(dsn, schema, payload, bifrost=False):
    tables=[t for t in payload['tables'] if t['name']!='sqlite_sequence']
    report=[]
    with connect(dsn) as connection:
        connection.execute(sql.SQL('SET LOCAL search_path TO {}, pg_catalog').format(sql.Identifier(schema)))
        connection.execute("SET LOCAL TIME ZONE 'UTC'")
        connection.execute('SET LOCAL extra_float_digits=3')
        existing=connection.execute('SELECT tablename FROM pg_tables WHERE schemaname=%s',(schema,)).fetchall()
        verify_only=bool(existing)
        if verify_only and {r[0] for r in existing}!={t['name'] for t in tables}:
            raise RuntimeError('Target schema has unexpected tables; refusing to overwrite live data.')
        kinds={}
        for table in tables:
            name=table['name']; primary=[c[1] for c in sorted(table['columns'],key=lambda c:c[5]) if c[5]]
            fields=[]; kinds[name]=[]
            for _,field,declared,notnull,default,pk in table['columns']:
                identity=primary==[field] and 'int' in declared.lower()
                kind=pgtype(declared,name,field,identity)
                # Caspy INTEGER flags are intentionally integer; only Bifrost
                # GORM's numeric/boolean columns are actual Postgres booleans.
                kinds[name].append(kind)
                definition=sql.SQL('{} {}').format(sql.Identifier(field),sql.SQL(kind))
                if notnull: definition+=sql.SQL(' NOT NULL')
                if default is not None and not identity:
                    if kind=='BOOLEAN':
                        val=default.strip('()').strip("'").lower(); definition+=sql.SQL(' DEFAULT ')+sql.Literal(val in ('1','true'))
                    else:
                        # Source DDL is local trusted schema, never user text.
                        if ';' in default: raise RuntimeError('Unexpected default expression')
                        if default.startswith('"') and default.endswith('"'):
                            definition+=sql.SQL(' DEFAULT ')+sql.Literal(default[1:-1].replace('""','"'))
                        else:
                            definition+=sql.SQL(' DEFAULT '+default)
                fields.append(definition)
            if primary: fields.append(sql.SQL('PRIMARY KEY ({})').format(sql.SQL(',').join(map(sql.Identifier,primary))))
            if verify_only: continue
            connection.execute(sql.SQL('CREATE TABLE {} ({})').format(sql.Identifier(name),sql.SQL(',').join(fields)))
            if not bifrost:
                connection.execute(sql.SQL('ALTER TABLE {} ENABLE ROW LEVEL SECURITY').format(sql.Identifier(name)))
            for number,index in enumerate(table['indexes']):
                if index.get('ddl'):
                    # SQLite/GORM's ordinary and partial B-tree index SQL is
                    # portable after replacing identifier backticks. Refuse
                    # unsupported SQLite-specific functions, never discard them.
                    definition=index['ddl'].replace('`','"').strip().rstrip(';')
                    if ';' in definition or re.search(r'\b(json_extract|strftime|ifnull)\s*\(',definition,re.I):
                        raise RuntimeError('SQLite-specific index needs an explicit conversion.')
                    connection.execute(definition)
                    continue
                if any(part[1]<0 for part in index['parts']):
                    raise RuntimeError('Unknown expression index; no data removed.')
                cols=[part[2] for part in index['parts']]
                if cols==primary: continue
                index_name=f'{name}_migrated_{number}'
                connection.execute(sql.SQL('CREATE {} INDEX {} ON {} ({})').format(
                    sql.SQL('UNIQUE' if index['unique'] else ''),sql.Identifier(index_name),sql.Identifier(name),sql.SQL(',').join(map(sql.Identifier,cols))))
        for table in tables:
            name=table['name']; columns=[c[1] for c in table['columns']]
            converted=[tuple(cell(v,k) for v,k in zip(row,kinds[name])) for row in table['rows']]
            if converted and not verify_only:
                query=sql.SQL('INSERT INTO {} ({}) VALUES ({})').format(sql.Identifier(name),sql.SQL(',').join(map(sql.Identifier,columns)),sql.SQL(',').join(sql.Placeholder() for _ in columns))
                with connection.cursor() as cursor: cursor.executemany(query,converted)
            got=connection.execute(sql.SQL('SELECT {} FROM {}').format(sql.SQL(',').join(map(sql.Identifier,columns)),sql.Identifier(name))).fetchall()
            expected_hash=digest(sorted(digest(row) for row in converted)); actual_hash=digest(sorted(digest(row) for row in got))
            if expected_hash!=actual_hash:
                by_key={row[0]:row for row in got}
                for before in converted:
                    after=by_key.get(before[0])
                    if after is not None:
                        for field,left,right in zip(columns,before,after):
                            if digest(left)!=digest(right):
                                raise RuntimeError('Native verification mismatch: '+name+'.'+field+' ('+type(left).__name__+' vs '+type(right).__name__+')')
                raise RuntimeError('Native row verification failed for '+name)
            for column,kind in zip(columns,kinds[name]):
                if 'IDENTITY' in kind and not verify_only:
                    sequence=connection.execute('SELECT pg_get_serial_sequence(%s,%s)',(schema+'.'+name,column)).fetchone()[0]
                    maximum=max((r[columns.index(column)] for r in converted),default=0)
                    connection.execute('SELECT setval(%s::regclass,%s,%s)',(sequence,max(1,maximum),bool(maximum)))
            report.append({'table':name,'rows':len(got),'sha256':actual_hash})
        # Foreign keys are created after all tables/data, preserving cycles.
        for table in tables:
            if verify_only: continue
            groups={}
            for fk in table['foreign_keys']: groups.setdefault(fk[0],[]).append(fk)
            for number,keys in groups.items():
                keys.sort(key=lambda r:r[1]); target=keys[0][2]
                action=keys[0][6].upper()
                if action not in ('CASCADE','RESTRICT','NO ACTION','SET NULL','SET DEFAULT'): raise RuntimeError('Unknown FK action')
                connection.execute(sql.SQL('ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({}) ON DELETE {} DEFERRABLE INITIALLY DEFERRED').format(
                    sql.Identifier(table['name']),sql.Identifier(f'{table["name"]}_migrated_fk_{number}'),
                    sql.SQL(',').join(sql.Identifier(k[3]) for k in keys),sql.Identifier(target),
                    sql.SQL(',').join(sql.Identifier(k[4]) for k in keys),sql.SQL(action)))
    return report


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply',action='store_true')
    parser.add_argument('--delete-sqlite',action='store_true')
    args=parser.parse_args()
    stopped(); env=environment(ROOT); dsn=database_url(env)
    paths=discovered()
    if not args.apply:
        print(json.dumps({'sqlite_files':[str(p.relative_to(ROOT)) for p in paths]},indent=2)); return
    if not paths: raise RuntimeError('No SQLite sources found; refusing an empty migration.')
    payloads={str(p.relative_to(ROOT)):snapshot(p) for p in paths}
    state_path=ROOT/'data/supabase-migration-state.json'
    destination=hashlib.sha256(dsn.encode()).hexdigest()
    if state_path.exists():
        state=json.loads(state_path.read_text())
        if state['destination']!=destination: raise RuntimeError('Migration destination changed; refusing to reuse state.')
        roles=state['roles']
    else:
        roles={schema:secrets.token_urlsafe(36) for schema in ('caspy_bifrost_config','caspy_bifrost_logs')}
        private_write(state_path,json.dumps({'destination':destination,'roles':roles})+'\n')
    with connect(dsn) as connection:
        connection.execute('CREATE SCHEMA IF NOT EXISTS caspy_archive')
        connection.execute('REVOKE ALL ON SCHEMA caspy_archive FROM PUBLIC, anon, authenticated')
        connection.execute('CREATE TABLE IF NOT EXISTS caspy_archive.sqlite_exports (file_path TEXT PRIMARY KEY, payload JSONB NOT NULL, sha256 TEXT NOT NULL, created TIMESTAMPTZ NOT NULL DEFAULT now())')
        connection.execute('ALTER TABLE caspy_archive.sqlite_exports ENABLE ROW LEVEL SECURITY')
        for name,payload in payloads.items():
            existing=connection.execute('SELECT sha256 FROM caspy_archive.sqlite_exports WHERE file_path=%s',(name,)).fetchone()
            if existing and existing[0]!=digest(payload): raise RuntimeError('Archive has a different snapshot; refusing to overwrite it.')
            connection.execute('INSERT INTO caspy_archive.sqlite_exports(file_path,payload,sha256) VALUES (%s,%s,%s) ON CONFLICT(file_path) DO NOTHING',(name,Jsonb(payload),digest(payload)))
            saved=connection.execute('SELECT payload FROM caspy_archive.sqlite_exports WHERE file_path=%s',(name,)).fetchone()[0]
            if digest(saved)!=digest(payload): raise RuntimeError('Lossless archive verification failed.')
        connection.execute('CREATE SCHEMA IF NOT EXISTS caspy')
        connection.execute('REVOKE ALL ON SCHEMA caspy FROM PUBLIC, anon, authenticated')
        for role,password in roles.items():
            if connection.execute('SELECT 1 FROM pg_roles WHERE rolname=%s',(role,)).fetchone():
                if not state_path.exists(): raise RuntimeError('Unexpected existing role')
            else:
                connection.execute(sql.SQL('CREATE ROLE {} LOGIN PASSWORD {}').format(sql.Identifier(role),sql.Literal(password)))
            owner=connection.execute('SELECT current_user').fetchone()[0]
            connection.execute(sql.SQL('GRANT {} TO {}').format(sql.Identifier(role),sql.Identifier(owner)))
            connection.execute(sql.SQL('CREATE SCHEMA IF NOT EXISTS {} AUTHORIZATION {}').format(sql.Identifier(role),sql.Identifier(role)))
            connection.execute(sql.SQL('REVOKE ALL ON SCHEMA {} FROM PUBLIC, anon, authenticated').format(sql.Identifier(role)))
            connection.execute(sql.SQL('ALTER ROLE {} SET search_path TO {}, pg_catalog').format(sql.Identifier(role),sql.Identifier(role)))
            connection.execute(sql.SQL('ALTER ROLE {} SET extra_float_digits=3').format(sql.Identifier(role)))
    # Archives commit before native imports; on any failure SQLite remains intact.
    print('Lossless archives committed and verified for',len(payloads),'SQLite files.',flush=True)
    report={'backend':'supabase-postgresql','sqlite_removed':False,'archives':{},'schemas':{}}
    for name,payload in payloads.items(): report['archives'][name]={'sha256':digest(payload),'rows':sum(len(t['rows']) for t in payload['tables'])}
    report['schemas']['caspy']=import_native(dsn,'caspy',payloads['data/platform.sqlite3'])
    print('Caspy native tables verified.',flush=True)
    for schema,filename in (('caspy_bifrost_config','caspy-bifrost.db'),('caspy_bifrost_logs','caspy-bifrost-logs.db')):
        report['schemas'][schema]=import_native(role_url(dsn,schema,roles[schema]),schema,payloads['data/'+filename],True)
        print(schema,'native tables verified.',flush=True)
    with connect(role_url(dsn,'caspy_bifrost_logs',roles['caspy_bifrost_logs'])) as connection:
        connection.execute((ROOT/'scripts/sql/bifrost_postgres.sql').read_text(),prepare=False)
        if connection.execute("SELECT bifrost_safe_jsonb('[1,2]')").fetchone()[0]!='[2]':
            raise RuntimeError('Bifrost PostgreSQL helper verification failed.')
    # Persist dedicated Bifrost log/config roles only after native verification.
    config=json.loads((ROOT/'data/config.json').read_text()); url=urlsplit(dsn)
    updates={}
    for key,schema in (('config_store','caspy_bifrost_config'),('logs_store','caspy_bifrost_logs')):
        prefix='CASPY_BF_CONFIG' if key=='config_store' else 'CASPY_BF_LOGS'
        cfg={'host':'env.'+prefix+'_HOST','port':'env.'+prefix+'_PORT','user':'env.'+prefix+'_USER','password':'env.'+prefix+'_PASSWORD','db_name':'env.'+prefix+'_DATABASE','ssl_mode':'require','max_idle_conns':1,'max_open_conns':3}
        config[key]={'enabled':True,'type':'postgres','config':cfg}
        role_dsn=urlsplit(role_url(dsn,schema,roles[schema]))
        updates.update({prefix+'_HOST':url.hostname,prefix+'_PORT':str(url.port or 5432),prefix+'_USER':unquote(role_dsn.username),prefix+'_PASSWORD':roles[schema],prefix+'_DATABASE':url.path.lstrip('/')})
    import shlex
    env_text=(ROOT/'.env').read_text()
    for key,value in updates.items():
        line=key+'='+shlex.quote(value)
        env_text=re.sub(r'(?m)^'+key+r'=.*$',lambda _:line,env_text) if re.search(r'(?m)^'+key+'=',env_text) else env_text.rstrip()+'\n'+line+'\n'
    private_write(ROOT/'.env',env_text)
    private_write(ROOT/'data/config.json',json.dumps(config,indent=2)+'\n')
    # Keep a non-SQLite, private local recovery export as well as remote archives.
    private_write(ROOT/'data/supabase-migration-recovery.json',json.dumps(payloads,ensure_ascii=False)+'\n')
    if args.delete_sqlite:
        stopped()
        for path in paths:
            if digest(snapshot(path))!=report['archives'][str(path.relative_to(ROOT))]['sha256']:
                raise RuntimeError('SQLite source changed after migration; refusing deletion.')
        for path in paths:
            for suffix in ('','-wal','-shm','-journal'):
                Path(str(path)+suffix).unlink(missing_ok=True)
        report['sqlite_removed']=True
    private_write(ROOT/'data/supabase-migration-report.json',json.dumps(report,indent=2)+'\n')
    print(json.dumps({'verified_schemas':list(report['schemas']),'archived_files':len(payloads),'archived_rows':sum(r['rows'] for r in report['archives'].values()),'sqlite_removed':report['sqlite_removed']}))


if __name__=='__main__':
    try: main()
    except Exception as error:
        # Driver exceptions may include passwords or row values. Never print them.
        detail=str(error) if isinstance(error,RuntimeError) else 'driver/row details hidden'
        if isinstance(error,psycopg.Error) and error.diag.message_primary:
            detail=re.sub(r"'[^']*'", "'[hidden]'",error.diag.message_primary)
        print('Migration stopped safely:',type(error).__name__,getattr(error,'sqlstate',''),detail)
        raise SystemExit(1)
